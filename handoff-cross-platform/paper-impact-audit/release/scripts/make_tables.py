def J(path):
    return json.loads(Path(path).read_text())


def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else float(beta.ppf(a / 2, k, n - k + 1))
    hi = 1.0 if k == n else float(beta.ppf(1 - a / 2, k + 1, n - k))
    return lo, hi


def fp(p):
    if p is None:
        return "--"
    if p < 0.001:
        s = f"{p:.2g}"
        if "e" not in s:
            return s
        m, e = s.split("e")
        return rf"${m}\times10^{{{int(e)}}}$"
    return f"{p:.3f}"


def fp_str(s):
    """Re-typeset a p-value string from consolidated-results.md."""
    s = s.strip()
    if s in ("–", "-", ""):
        return "--"
    if "e" in s:
        m, e = s.split("e")
        return rf"${m}\times10^{{{int(e)}}}$"
    return s


def esc(s):
    s = s.replace("\\", r"\textbackslash{}").replace("**", "").replace("`", "")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}")):
        s = s.replace(a, b)
    s = s.replace("^", r"\textasciicircum{}").replace("–", "--")
    s = s.replace(">=", r"$\geq$").replace("<=", r"$\leq$").replace(">", "$>$").replace("<", "$<$")
    s = re.sub(r"(\d)x(\d)", r"\1$\\times$\2", s)
    s = re.sub(r"'([^']+)'", r"`\1'", s)
    s = s.replace(r"h0\textasciicircum{}2 - (h0 - 0.1)\textasciicircum{}2", r"$h_0^2-(h_0-0.1)^2$")
    s = s.replace(r"+D(h\_t)", r"$+D(h_t)$").replace("evaluate()", r"\texttt{evaluate()}")
    return s


def kname(s):
    """KeyCorridor runs are C1-C6 in the project records and K1-K6 in the paper (C1-C5 are the paper's claim labels)."""
    return re.sub(r"\bC([1-6])\b", r"K\1", s)


def f3(x):
    return f"{x:.3f}"


def write(name, body):
    OUT.mkdir(exist_ok=True)
    (OUT / name).write_text("% Generated by paper/scripts/make_tables.py. Do not edit by hand.\n" + body)


