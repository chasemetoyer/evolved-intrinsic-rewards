def plain(cell):
    """LaTeX cell -> plain text for the CSV."""
    m = re.match(r"\\multicolumn\{\d+\}\{(?:@\{\})?[lcr](?:@\{\})?\}\{(.*)\}$", cell)
    c = m.group(1) if m else cell
    for a, b in ((r"$\to$", "->"), (r"$^\dagger$", "\u2020"), (r"$>$", ">"), (r"$-$", "-"), ("~", " "), (r"\$", "$"),
                 (r"\%", "%"), (r"\_", "_"), (r"\textbf{", ""), (r"\textit{", ""), ("$U$", "U"), ("$p$", "p"),
                 ("$m$", "m"), ("$P_0$", "P0"), ("$h_0$", "h0"), (r"\times10^{", "e"), (r"\rho", "rho"), (r"\gamma", "gamma"),
                 (r"\lambda", "lambda"), ("$", ""), ("}", ""), ("{", "")):
        c = c.replace(a, b)
    return c.strip()


def csv_text(header, rows):
    import csv as _csv, io
    out, group = io.StringIO(), ""
    w = _csv.writer(out, lineterminator="\n")
    w.writerow(["group"] + [plain(h) for h in header])
    for r in rows:
        if r in ("SEP", "RULE"):
            continue
        if len(r) == 1:
            group = plain(r[0])
            continue
        w.writerow([group] + [plain(c) for c in r])
    return out.getvalue()
NAMES = {"E": "E (CMA-ES-selected)", "R": "R (random-search-selected)", "T": "T (task-only)",
         "N": "N (episodic novelty)", "S": r"S (satiation)$^\dagger$"}


def tabular(spec, header, rows, note=None):
    _LAST["csv"] = csv_text(header, rows)
    lines = [HEAD + rf"\begin{{tabular}}{{{spec}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for r in rows:
        lines.append(r"\addlinespace" if r == "SEP" else (r"\midrule" if r == "RULE" else " & ".join(r) + r" \\"))
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def calibration():
    s1 = M.J(SRC / "s1-numbers.json")
    rows = []
    for r in s1["calibration"]["selection"]:
        budget = "1M" if r["role"] == "training" else "2M"
        reason = "; ".join(r["reasons"]).replace("Best baseline mean curve area", "best baseline area") or "--"
        reason = reason.replace("best baseline area exceeds 0.85", "too easy (area $>0.85$)").replace(
            "best baseline area is below 0.05", "too hard (area $<0.05$)")
        role = "training" if r["role"] == "training" else "held out"
        rows.append([r["task"], role, budget, M.f(r["best_mean_curve_area"]), r["status"], reason])
    return tabular("@{}lllrll@{}", ["Task", "Candidate role", "Budget", "Best baseline area", "Outcome", "Reason"], rows)


def finalists():
    rows = []
    for r in M.C("s2-finalists.csv"):
        meth = "CMA-ES" if r["method"] == "cma" else "Random search"
        win = (r["method"], r["candidate"]) in (("cma", "113"), ("random", "57"))
        cand = r["candidate"] + (r" (\textbf{E})" if win and r["method"] == "cma" else r" (\textbf{R})" if win else "")
        rows.append([meth, cand, M.f(r["search_fitness"]), M.f(r["reevaluated_fitness"]),
                     M.sg(float(r["reevaluated_fitness"]) - float(r["search_fitness"])),
                     M.f(r["DoorKey-8x8_area"]), f"{M.n(r['DoorKey-8x8_solved'])}/10",
                     M.f(r["UnlockPickup_area"]), f"{M.n(r['UnlockPickup_solved'])}/10"])
    return tabular("@{}llrrrrrrr@{}", ["Method", "Candidate", "Search", "Re-eval.", "Change",
                                       "DK area", "DK solved", "UP area", "UP solved"], rows)


def final_eval():
    cells = M.C("s3-cells.csv")
    rows = []
    for tk, task in M.TASKS.items():
        label = task + (" (held out)" if tk == "kc" else " (training)")
        rows.append([rf"\multicolumn{{5}}{{@{{}}l}}{{\textit{{{label}}}}}"])
        for m in M.METHODS:
            r = M.one(cells, method=m, task=task)
            rows.append([NAMES[m], f"{M.f(r['mean_area'])} ({M.f(r['sd_area'])})", f"{M.n(r['solve_count'])}/{M.n(r['n'])}",
                         f"[{float(r['solve_ci95_lower']):.2f}, {float(r['solve_ci95_upper']):.2f}]",
                         M.steps(r["median_censored_first_solved_step"])])
        rows.append("SEP")
    rows.pop()
    return tabular("@{}lrrrr@{}", ["Method", "Mean area (SD)", "Solved", "95\\% CI (solved)", "Median first solve"], rows)


def comparisons():
    comp, fish = M.C("s3-comparisons.csv"), M.C("s3-fisher.csv")
    rows = []
    for fam, tasks in (("primary", ("KeyCorridorS3R2",)), ("secondary", ("DoorKey-8x8", "UnlockPickup"))):
        size = M.one(comp, family=fam, task=tasks[0], comparator="T")["family_size"]
        label = "Primary family, held-out task" if fam == "primary" else "Secondary family, training tasks"
        rows.append([rf"\multicolumn{{9}}{{@{{}}l}}{{\textit{{{label} (Holm, $m$={size})}}}}"])
        for task in tasks:
            for c in ("T", "N", "R"):
                r = M.one(comp, family=fam, task=task, comparator=c)
                fr = M.one(fish, task=task, comparison=f"E > {c}")
                rows.append([task, f"E $>$ {c}", M.sg(r["mean_difference"]), M.f(r["U"], 1),
                             M.fp(float(r["raw_p"])), M.fp(float(r["holm_adjusted_p"])),
                             r"\textbf{hit}" if r["rank_hit"] == "True" else r"\textbf{miss}",
                             "yes" if r["meaningful_improvement"] == "True" else "no",
                             M.fp(float(fr["descriptive_one_sided_fisher_p"]))])
        rows.append("SEP")
    rows.pop()
    return tabular("@{}llrrrrllr@{}", ["Task", "Test", "Mean gap", "$U$", "Raw $p$", "Holm $p$", "Rank test",
                                     "Meaningful", "Fisher $p$"], rows)


