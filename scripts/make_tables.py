def main(only=None):
    M.main()
    OUT.mkdir(parents=True, exist_ok=True)
    RESULTS.mkdir(exist_ok=True)
    written = {}
    for name, fn in TABLES.items():
        if only and NUMBER[name] != only:
            continue
        tex = fn()
        written[f"tables/{name}.tex"] = tex
        written[f"results/table{NUMBER[name]}_{name}.csv"] = _LAST["csv"]
    return written


if __name__ == "__main__":
    only = int(sys.argv[sys.argv.index("--table") + 1]) if "--table" in sys.argv else None
    for rel, text in main(only).items():
        (M.PAPER / rel if rel.startswith("tables/") else ROOT / rel).write_text(text)
    print("wrote", ", ".join(sorted(main(only))))
