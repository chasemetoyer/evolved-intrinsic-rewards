"""Generate every table: paper/tables/<name>.tex for the paper and results/tableN_<name>.csv for readers.

Each table is a bare tabular; its float, caption and label live in paper.tex. Formatting helpers are shared with
make_numbers.py, so a value printed in a table and in the prose is the same string. check_numbers.py regenerates
these files in memory and fails on any difference.

Each CSV holds exactly the cells of its LaTeX table, with markup removed; group-heading rows go in a "group" column.

Usage (repo root): make tables   (or: python3 scripts/make_tables.py [--table N])
"""
